#!/usr/bin/env python3
"""
Exporters Module
Write output files: JSONL, CSV, Markdown
"""

import json
import csv
import pandas as pd
from pathlib import Path
from typing import List, Dict
from datetime import datetime

from .dedupe import Venue


def export_venues_jsonl(venues: List[Venue], output_path: Path, baseline_venues: List[Venue] = None):
    """Export all venues (baseline + new) to JSONL"""
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    with open(output_path, 'w', encoding='utf-8') as f:
        # Write baseline first
        if baseline_venues:
            for v in baseline_venues:
                record = {
                    'venue_id': v.venue_id,
                    'name': v.name,
                    'lat': v.lat,
                    'lng': v.lng,
                    'rating': v.rating,
                    'raw_text': v.raw_text,
                    'corridors': v.corridors,
                    'source': v.source,
                    'query_found_by': v.query_found_by,
                    'category': v.category,
                    'road_name': v.road_name,
                    'tier': v.tier
                }
                f.write(json.dumps(record, ensure_ascii=False) + '\n')
        
        # Write new venues
        for v in venues:
            record = {
                'venue_id': v.venue_id,
                'name': v.name,
                'lat': v.lat,
                'lng': v.lng,
                'rating': v.rating,
                'raw_text': v.raw_text,
                'corridors': v.corridors,
                'source': v.source,
                'query_found_by': v.query_found_by,
                'category': v.category,
                'road_name': v.road_name,
                'tier': v.tier
            }
            f.write(json.dumps(record, ensure_ascii=False) + '\n')


def export_coverage_report(corridor_stats: List[Dict], output_path: Path):
    """Export coverage report CSV"""
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    df = pd.DataFrame(corridor_stats)
    df.to_csv(output_path, index=False)


def export_error_log(errors: List[Dict], output_path: Path):
    """Export error log CSV"""
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    if errors:
        df = pd.DataFrame(errors)
        df.to_csv(output_path, index=False)
    else:
        # Empty file with headers
        pd.DataFrame(columns=['timestamp', 'corridor_id', 'point_id', 'query', 'error_type', 'details']).to_csv(output_path, index=False)


def export_ringkasan_md(
    total_venues: int,
    total_new_venues: int,
    baseline_venues: int,
    corridors_saturated: int,
    total_corridors: int,
    actual_cost_estimate: float,
    limitations: List[str],
    output_path: Path
):
    """Export summary markdown"""
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    pct_saturated = (corridors_saturated / total_corridors * 100) if total_corridors > 0 else 0
    
    md = f"""# Google Maps Sweep Summary - Yogyakarta Corridors

**Generated:** {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}

## Overview

| Metric | Value |
|--------|-------|
| Total Corridors | {total_corridors} |
| Corridors with Saturation Achieved | {corridors_saturated} ({pct_saturated:.1f}%) |
| Baseline Venues (7 categories) | {baseline_venues:,} |
| New Venues Discovered (all categories) | {total_new_venues:,} |
| **Total Unique Venues** | **{total_venues:,}** |
| Estimated Cost | ${actual_cost_estimate:,.2f} |

## Limitations & Caveats

"""
    for lim in limitations:
        md += f"- {lim}\n"
    
    md += f"""

## Notes

- **Saturation ≠ 100% completeness**: Saturation means 10 consecutive queries added 0 new venues. Unlisted or unsearchable businesses may exist.
- **Baseline preserved**: Original 3,601 venues from 7 categories unchanged.
- **Source tracking**: Each new venue tagged with `source="sweep_v2"` and the query that found it.
- **Deduplication**: Name normalization + 15m coordinate threshold used.

## Data Files

- `venues_sweep_v2.jsonl` — All venues (baseline + new) with full metadata
- `coverage_report.csv` — Per-corridor statistics and saturation status
- `error_log.csv` — All errors, CAPTCHAs, timeouts, suspected truncations

---
*Generated by gmaps_sweep_browser v1.0*
"""
    
    output_path.write_text(md, encoding='utf-8')


def export_progress_log(progress: Dict, output_path: Path):
    """Append progress to log file"""
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    with open(output_path, 'a', encoding='utf-8') as f:
        f.write(json.dumps(progress, ensure_ascii=False) + '\n')